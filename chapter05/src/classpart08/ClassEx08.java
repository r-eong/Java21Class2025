package classpart08;

public class ClassEx08 {
	int x;
	int y;
	
//	+ 더하기
	public int add(int x, int y) {
		return x + y;
	}
	
//	- 빼기
	public int del(int x, int y) {
		return x - y;
	}
	
//	* 곱하기
	public int avg(int x, int y) {
		return x * y;
	}
	
//	* 곱하기
	public int nanugi(int x, int y) {
		return x / y;
	}
}
